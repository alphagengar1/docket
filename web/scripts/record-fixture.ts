// Records one full mock run (persona P02, then a human approval of the CU offer) into src/mock/fixture.ts.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { simulateDesk } from '../src/mock/engine'
import { personaById } from '../src/mock/personas'
import type { Applicant } from '../src/types'
import type { TimedOp } from '../src/mock/store'

const persona = personaById('P02')!
const t0 = Date.UTC(2026, 9, 24, 9, 30, 0)
const applicant: Applicant = {
  _id: 'app_replay',
  personaId: persona.personaId,
  name: persona.name,
  ...persona.defaults,
  consentAt: t0,
  status: 'intake',
  createdAt: t0,
}
let n = 0
const ops: TimedOp[] = simulateDesk(applicant, persona, {
  t0,
  ids: {
    bundle: 'bun_replay',
    offers: { cu: 'off_replay_cu', fintech: 'off_replay_fintech', prime: 'off_replay_prime' },
    notice: 'not_replay',
    audit: () => `aud_replay_${(n++).toString().padStart(2, '0')}`,
  },
})
const last = Math.max(...ops.map((o) => o.atMs))
const approveAt = last + 4000
const cu = ops.filter((o) => o.op.kind === 'offer.upsert' && o.op.row.lender === 'cu').at(-1)!.op as Extract<TimedOp['op'], { kind: 'offer.upsert' }>
ops.push({
  atMs: approveAt,
  op: {
    kind: 'decision.insert',
    row: { _id: 'dec_replay', applicantId: applicant._id, chosenOfferId: cu.row._id, outcome: 'approved', approvedBy: 'human', at: t0 + approveAt, note: `Approved cu offer: ${cu.row.apr}% APR, ${cu.row.termMonths} mo, $${cu.row.amount?.toLocaleString('en-US')}. (recorded)` },
  },
})
ops.push({ atMs: approveAt, op: { kind: 'applicant.status', id: applicant._id, status: 'approved' } })
ops.push({ atMs: approveAt, op: { kind: 'audit.insert', row: { _id: `aud_replay_${n++}`, applicantId: applicant._id, at: t0 + approveAt, actor: 'human', action: 'offer.approved', ref: `offers.${cu.row._id}`, note: 'Recorded replay approval.' } } })
ops.push({ atMs: approveAt, op: { kind: 'audit.insert', row: { _id: `aud_replay_${n++}`, applicantId: applicant._id, at: t0 + approveAt, actor: 'desk', action: 'step.human.done', ref: null, note: 'Decision recorded.' } } })

const out = `// Recorded run used by Replay mode. Generated by scripts/record-fixture.ts; do not edit by hand.
import type { TimedOp } from './store'

export interface Fixture {
  t0: number
  personaId: string
  ops: TimedOp[]
}

export const FIXTURE: Fixture = ${JSON.stringify({ t0, personaId: persona.personaId, ops }, null, 2)}
`
const here = dirname(fileURLToPath(import.meta.url))
writeFileSync(resolve(here, '../src/mock/fixture.ts'), out)
console.log(`wrote ${ops.length} ops`)
