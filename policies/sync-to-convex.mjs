// Regenerates convex/policies.ts from policies/*.md so the Convex bundle can
// embed the prompt text (Convex functions cannot read the filesystem).
// Run: npm run policies:sync
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const lenders = ["cu", "fintech", "prime"];
const parts = lenders.map((l) => {
  const md = readFileSync(join(here, `${l}.md`), "utf8");
  return `  ${l}: ${JSON.stringify(md)},`;
});
const out = `// GENERATED by policies/sync-to-convex.mjs from policies/*.md. Do not edit by hand.
// Teammate edits policies/*.md, then: npm run policies:sync
import type { Lender } from "./types";

export const POLICIES: Record<Lender, string> = {
${parts.join("\n")}
};

export const LENDER_NAMES: Record<Lender, string> = {
  cu: "Pacific Ridge Credit Union",
  fintech: "Northstar Lending",
  prime: "Meridian Bank Prime",
};
`;
writeFileSync(join(here, "..", "convex", "policies.ts"), out);
console.log("wrote convex/policies.ts");
